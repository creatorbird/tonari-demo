type Vars = Record<string, string>;

function format(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => vars[name] ?? `{${name}}`);
}

/** 指定した言語の文言（未対応の言語は英語） */
export function t(lang: string, key: MessageKey, vars?: Vars): string {
  return format((DICTIONARIES[lang] ?? en)[key], vars);
}

export type BilingualText = {
  /** 選択した言語での文言 */
  primary: string;
  /** 英語の文言（選択言語が英語なら null） */
  english: string | null;
};

/** 選択した言語と英語の両方の文言 */
export function bi(lang: string, key: MessageKey, vars?: Vars): BilingualText {
  const primary = t(lang, key, vars);
  const english = t("en", key, vars);
  return { primary, english: primary === english ? null : english };
}

/** 属性値（placeholder など）用に「選択言語 / English」の1行にまとめる */
export function biInline(lang: string, key: MessageKey, vars?: Vars): string {
  const { primary, english } = bi(lang, key, vars);
  return english ? `${primary} / ${english}` : primary;
}

/** 言語名を差し込む文言用のヘルパー */
export function langVar(code: string): Vars {
  return { lang: languageLabel(code) };
}
